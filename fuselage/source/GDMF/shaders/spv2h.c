// Embed little-endian SPIR-V as aligned, read-only C words.
// SEE: (GDMF_VULKAN.md, Embedded shader headers).
#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

static bool gdmf_shader_identifier(const char* symbol) {
    for (size_t character = 0; symbol[character]; character++) {
        char value = symbol[character];
        bool letter = (value >= 'a' && value <= 'z') || (value >= 'A' && value <= 'Z') || value == '_';
        if (!letter && (character == 0 || value < '0' || value > '9')) { return false; }
    }
    return *symbol != '\0';
}

static bool gdmf_shader_write_header(FILE* output, const unsigned char* bytes,
    size_t byte_count, const char* symbol) {
    char guard[260];
    size_t symbol_length = strlen(symbol);
    for (size_t character = 0; character < symbol_length; character++) {
        char value = symbol[character];
        guard[character] = value >= 'a' && value <= 'z' ? (char)(value - 'a' + 'A') : value;
    }
    memcpy(guard + symbol_length, "_H", 3);
    if (fprintf(output,
        "#ifndef %s\n#define %s\n\n"
        "// Generated by spv2h. Do not edit the word data.\n"
        "// SEE: (GDMF_VULKAN.md, Embedded shader headers).\n"
        "#include <stdint.h>\n#include <stddef.h>\n\n"
        "static const uint32_t %s[] = {\n", guard, guard, symbol) < 0) { return false; }
    for (size_t offset = 0; offset < byte_count; offset += 4) {
        uint32_t word = (uint32_t)bytes[offset] | ((uint32_t)bytes[offset + 1] << 8) |
            ((uint32_t)bytes[offset + 2] << 16) | ((uint32_t)bytes[offset + 3] << 24);
        if (offset % 24 == 0 && fprintf(output, "    ") < 0) { return false; }
        if (fprintf(output, "0x%08xu,", (unsigned int)word) < 0) { return false; }
        if (fprintf(output, "%s", (offset + 4 == byte_count || (offset + 4) % 24 == 0) ? "\n" : " ") < 0) { return false; }
    }
    return fprintf(output, "};\nstatic const size_t %s_byte_count = sizeof(%s);\n\n#endif // %s\n",
        symbol, symbol, guard) >= 0;
}

int main(int argument_count, char* arguments[]) {
    if (argument_count != 3 && argument_count != 4) {
        fprintf(stderr, "usage: spv2h <input.spv> <output.h> [symbol]\n");
        return 1;
    }
    if (strcmp(arguments[1], arguments[2]) == 0) {
        fprintf(stderr, "spv2h: input and output paths must differ\n");
        return 1;
    }
    char symbol[256];
    if (argument_count == 4) {
        if (strlen(arguments[3]) >= sizeof symbol || !gdmf_shader_identifier(arguments[3])) {
            fprintf(stderr, "spv2h: invalid or oversized C identifier\n"); return 1;
        }
        memcpy(symbol, arguments[3], strlen(arguments[3]) + 1);
    } else {
        const char* basename = arguments[1];
        for (const char* character = arguments[1]; *character; character++) {
            if (*character == '/' || *character == '\\') { basename = character + 1; }
        }
        if (!*basename || strlen(basename) > sizeof symbol - sizeof "gdmf_") {
            fprintf(stderr, "spv2h: invalid or oversized basename\n"); return 1;
        }
        snprintf(symbol, sizeof symbol, "gdmf_%s", basename);
        for (char* character = symbol; *character; character++) {
            if (!((*character >= 'a' && *character <= 'z') || (*character >= 'A' && *character <= 'Z') ||
                (*character >= '0' && *character <= '9') || *character == '_')) { *character = '_'; }
        }
    }

    FILE* input = fopen(arguments[1], "rb");
    if (!input) { perror(arguments[1]); return 1; }
    long file_size = -1;
    if (fseek(input, 0, SEEK_END) == 0) { file_size = ftell(input); }
    if (file_size < 20 || file_size % 4 || (uintmax_t)file_size > SIZE_MAX || fseek(input, 0, SEEK_SET) != 0) {
        fprintf(stderr, "spv2h: input must contain a complete word-aligned SPIR-V header\n");
        fclose(input); return 1;
    }
    size_t byte_count = (size_t)file_size;
    unsigned char* bytes = malloc(byte_count);
    if (!bytes) { fprintf(stderr, "spv2h: out of memory\n"); fclose(input); return 1; }
    bool read_ok = fread(bytes, 1, byte_count, input) == byte_count;
    if (fclose(input) != 0) { read_ok = false; }
    if (!read_ok || bytes[0] != 0x03 || bytes[1] != 0x02 || bytes[2] != 0x23 || bytes[3] != 0x07) {
        fprintf(stderr, "spv2h: read error or unsupported SPIR-V byte order/magic\n");
        free(bytes); return 1;
    }
    FILE* output = fopen(arguments[2], "w");
    if (!output) { perror(arguments[2]); free(bytes); return 1; }
    bool written = gdmf_shader_write_header(output, bytes, byte_count, symbol);
    if (fclose(output) != 0) { written = false; }
    free(bytes);
    if (!written) { fprintf(stderr, "spv2h: header write failed\n"); return 1; }
    return 0;
}
